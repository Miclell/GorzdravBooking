import { test, expect } from '@playwright/test';

// Run only against the isolated demo API described in docs/ui-audit.md.
test('demo API: регистрация, пациент, шаблон, заявка, редактирование и выход', async ({ page }) => {
  const username = 'ui_' + Date.now();
  const password = 'AuditPass123';
  await page.goto('/register');
  await page.getByLabel('Логин', { exact: true }).fill(username);
  await page.getByLabel('Пароль', { exact: true }).fill(password);
  await page.getByLabel('Подтверждение пароля', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Зарегистрироваться', exact: true }).click();
  await expect(page).toHaveURL(/dashboard$/);
  await page.getByRole('button', { name: '+ Добавить пациента' }).click();
  await page.getByLabel('Район *', { exact: true }).selectOption({ index: 1 });
  await page.getByLabel('Поликлиника *', { exact: true }).selectOption({ index: 1 });
  await page.getByLabel('Фамилия *', { exact: true }).fill('Иванов');
  await page.getByLabel('Имя *', { exact: true }).fill('Иван');
  await page.getByLabel('Отчество *', { exact: true }).fill('Иванович');
  await page.getByLabel('Дата рождения *', { exact: true }).fill('1985-01-01');
  await page.getByRole('button', { name: 'Проверить данные в Городздрав', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Создать пациента', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Создать пациента', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Иванов Иван Иванович', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Временные предпочтения', exact: true }).click();
  await page.getByRole('button', { name: '+ Создать шаблон' }).click();
  await page.getByLabel('Название шаблона', { exact: true }).fill('Воскресенье');
  await page.getByRole('button', { name: 'По дням недели', exact: true }).click();
  await page.getByLabel('День', { exact: true }).first().selectOption('0');
  await page.getByRole('button', { name: 'Создать', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Изменить', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Редактировать шаблон');
  await expect.poll(() => page.getByLabel('День', { exact: true }).evaluateAll(elements => elements.map(element => element.value).sort())).toEqual(['0', '3']);
  await page.getByRole('button', { name: 'Закрыть модальное окно' }).click();
  await page.getByRole('button', { name: 'В рабочий кабинет', exact: true }).click();
  await page.getByRole('button', { name: /Заявки 0/, exact: true }).click();
  await page.getByRole('button', { name: '+ Создать заявку' }).click();
  await page.getByRole('button', { name: 'Вручную', exact: true }).click();
  await page.getByLabel('Пациент *', { exact: true }).selectOption({ index: 1 });
  await page.getByLabel('Специальность *', { exact: true }).selectOption({ index: 1 });
  await page.getByLabel('Шаблон времени *', { exact: true }).selectOption('Воскресенье');
  await page.getByRole('button', { name: 'Настройки поиска', exact: true }).click();
  await page.getByLabel('Только просмотр', { exact: false }).check();
  await page.getByRole('button', { name: 'Готово', exact: true }).click();
  await page.getByRole('button', { name: 'Создать заявку', exact: true }).click();
  await expect(page).toHaveURL(/dashboard$/);
  await expect(page.getByRole('status')).toContainText('Заявка создана');
  await page.getByRole('button', { name: /Иванов.*Ожидает/ }).click();
  await page.getByRole('button', { name: 'Изменить временные предпочтения', exact: true }).click();
  await page.getByRole('button', { name: 'Настройки поиска', exact: true }).click();
  await page.getByLabel('Интервал поиска (мин)', { exact: true }).fill('1440');
  await page.getByRole('button', { name: 'Готово', exact: true }).click();
  await page.getByRole('button', { name: 'Управление шаблонами', exact: true }).click();
  await page.getByRole('button', { name: '← Назад к заявке', exact: true }).click();
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click();
  await expect(page).toHaveURL(/dashboard$/);
  await expect(page.getByRole('status')).toContainText('Заявка обновлена');
  await page.getByRole('button', { name: 'Выйти из аккаунта', exact: true }).click();
  await expect(page).toHaveURL(/login$/);
  await page.getByLabel('Логин', { exact: true }).fill(username);
  await page.getByLabel('Пароль', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Войти в систему', exact: true }).click();
  await expect(page).toHaveURL(/dashboard$/);
});

